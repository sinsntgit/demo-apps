import json, re, sqlite3, statistics as st
from collections import Counter
from .config import SAMPLE, DOCS, DB_PATH, VERSIONS
from .lexicon import TEXT_SIGNALS, DERIVED_SIGNALS, FAMILY_CATEGORY, EVENT_RE
from .taxonomy import Taxonomy


def _walk(spans, fn, depth=0):
    for s in spans or []:
        if isinstance(s, dict):
            fn(s, depth)
            _walk(s.get("spans") if isinstance(s.get("spans"), list) else None, fn, depth + 1)


def profile():
    raw = open(SAMPLE, "rb").read()
    rows = [json.loads(l) for l in raw.splitlines() if l.strip()]
    n = len(rows)
    traces = [t for r in rows for t in (r.get("traces") or [])]
    ntr = [len(r.get("traces") or []) for r in rows]
    roles, tools, events, labels, ph, langs, stypes, depth = Counter(), Counter(), Counter(), Counter(), Counter(), Counter(), Counter(), Counter()
    nulls = sum(1 for t in traces if t.get("redacted_output") is None)
    diff = sum(1 for t in traces if t.get("input") != t.get("redacted_input") or t.get("output") != t.get("redacted_output"))
    for t in traces:
        try:
            for m in json.loads(t.get("redacted_output") or "[]"):
                roles[str(m.get("role")).lower()] += 1
        except Exception:
            roles["(unparseable)"] += 1
        u = " ".join(m.get("content", "") for m in json.loads(t.get("redacted_input") or "[]") if isinstance(m.get("content"), str))
        em = EVENT_RE.match(u)
        if em:
            b = em.group(2)
            events["dtmf" if "pressed" in b else "no_input" if "no user activity" in b else "function_result" if "function [" in b
                   else "session_start" if "session start" in b else "disconnect" if "disconnect" in b else "other"] += 1
        for x in re.findall(r"\[[A-Z_]{3,}\]", (t.get("redacted_input") or "") + (t.get("redacted_output") or "")):
            ph[x] += 1
        if re.search(r"\b(el día|cómo|qué|não)\b", u, re.I):
            langs["es/pt turn"] += 1

        def f(s, d):
            stypes[s.get("type")] += 1; depth[d] += 1
            if s.get("type") == "tool":
                tools[s.get("name")] += 1
                try:
                    c = json.loads(s.get("input") or "[]")[0].get("content")
                    if isinstance(c, dict) and c.get("intent_name"):
                        labels[c["intent_name"]] += 1
                except Exception:
                    pass
        _walk(t.get("spans"), f)
    smet = Counter(k for r in rows for k in (r.get("metrics") or {}))
    tmet = Counter(k for t in traces for k in (t.get("metrics") or {}))
    status = Counter(v for r in rows for k, v in (r.get("metrics") or {}).items() if k.endswith("_status"))
    errs = Counter(k[:-14] for r in rows for k, v in (r.get("metrics") or {}).items() if k.endswith("_error_message") and v)
    journeys = Counter()
    for r in rows:
        try:
            journeys[json.loads(r["metrics"]["cm_policy_metric"])["metrics"]["journey"]] += 1
        except Exception:
            journeys["(missing)"] += 1
    size = len(raw) / n
    spans_bytes = sum(len(json.dumps(t.get("spans"))) for t in traces) / len(raw)
    met_bytes = (sum(len(json.dumps(r.get("metrics"))) for r in rows) + sum(len(json.dumps(t.get("metrics"))) for t in traces)) / len(raw)
    created = sorted(r.get("created_at", "") for r in rows)
    turn_starts = Counter(min(int(m.group(1)) for t in r["traces"] if (m := re.search(r"turn (\d+)", t.get("name", "")))) == 1 for r in rows)
    pop = lambda key: sum(1 for r in rows if r.get(key) not in (None, "", {}, [])) / n
    L = [f"# Source data profile: real VzGPT sample", "", f"_Generated by `python -m cie.docs` from `{SAMPLE.name}` (git-ignored). Rules {VERSIONS['rules']}._", "",
         "## Shape", "", "| Item | Value |", "|---|---|",
         f"| Sessions (lines) | {n} |", f"| Traces (one per turn) | {len(traces)} |",
         f"| Traces per session | mean {st.mean(ntr):.2f}, median {st.median(ntr)}, min {min(ntr)}, max {max(ntr)} |",
         f"| Sessions whose window starts at turn 1 | {turn_starts[True]} of {n} (exports are windows; turn N can start at 2-14) |",
         f"| Time span | {created[0][:19]} -> {created[-1][:19]} (single day) |",
         f"| Raw size | {size / 1024:.0f} KB/session; nested spans {spans_bytes:.0%} of bytes, metrics {met_bytes:.0%} |",
         f"| Projected raw size at 100K sessions | {size * 1e5 / 1e9:.0f} GB raw (gzip ~5x smaller): raw is landed as files, not DB rows |",
         f"| Traces with null redacted_output | {nulls} ({nulls / len(traces):.0%}) |",
         f"| Traces where raw != redacted text | {diff} (redaction already applied upstream; we still re-scrub) |",
         f"| Session fields populated: previous_session_id / user_metadata / tags / num_traces | {pop('previous_session_id'):.0%} / {pop('user_metadata'):.0%} / {pop('tags'):.0%} / {pop('num_traces'):.0%} |",
         f"| Session metric fields | {len(smet)} distinct |", f"| Trace metric fields | {len(tmet)} distinct |", "",
         "## Conversation content", "", "Agent roles (from `output[].role`; case-normalised):", "",
         "| Role | Messages |", "|---|---|"] + [f"| `{k}` | {v} |" for k, v in roles.most_common()] + [
         "", "System events arriving as customer turns:", "", "| Event | Turns |", "|---|---|"] + [f"| {k} | {v} |" for k, v in events.most_common()] + [
         "", f"Redaction placeholders: " + ", ".join(f"`{k}` x{v}" for k, v in ph.most_common()), "",
         f"Non-English turns (Spanish/Portuguese markers): {langs['es/pt turn']}", "",
         "## Execution traces and tools", "", "Span types: " + ", ".join(f"{k} x{v}" for k, v in stypes.most_common()) + f"; nesting depth up to {max(depth)}.", "",
         "| Tool | Calls |", "|---|---|"] + [f"| `{k}` | {v} |" for k, v in tools.most_common()] + [
         "", "## Platform intent labels (`mandatory_set_intent_for_next_step.intent_name`)", "", "| intent_name | Calls |", "|---|---|"] + [
         f"| `{k}` | {v} |" for k, v in labels.most_common()] + [
         "", "## Evaluations", "", "Journeys (`cm_policy_metric.metrics.journey`): " + ", ".join(f"{k} x{v}" for k, v in journeys.most_common()), "",
         "Judge status values: " + ", ".join(f"{k} x{v}" for k, v in status.most_common()), "",
         "Metrics with an error message in at least one session: " + (", ".join(f"`{k}` x{v}" for k, v in errs.most_common()) or "none"), "",
         "## Findings that shape the design", "",
         "1. **Billing/IVR/authentication dominate** (confirmed representative). Expect risk/friction insights first; buying/value signals will be rarer.",
         "2. **The platform already labels intent** in tool spans (`intent_name`, agent paraphrases in `retrieve_intent_matches.user_intent` / `explain_bill_init_mcp.query`). These are the strongest evidence for the taxonomy, but several labels are generic routing labels (`bill_plus_operator`, `bill_problem_general`, `bill_explain_incorrect`, `RecentAccountActivity`) and must not override the customer's explicit words.",
         "3. **Turn order must be rebuilt** from `turn N`; windows start mid-call. Customer turns are often system events (DTMF, no-input, function results): friction evidence, not utterances.",
         "4. **Redaction is imperfect for display**: a place name and exact dollar amounts appear in redacted text. Quotes are re-masked before evidence cards.",
         "5. **Repeat-contact linkage** depends on `previous_session_id` (empty in the sample; confirmed available in production). **Location** is not in the export (an assumed contract is used until Verizon supplies it).",
         "6. **Some evaluators error** (e.g. a model-gateway 404): status must be kept and never coerced to 0.",
         "7. **Raw payload is ~0.5 MB/session**, mostly nested LLM spans. 100K sessions = ~56 GB raw, so raw lands as gzipped files with a lineage index."]
    return "\n".join(L) + "\n"


def signal_catalogue():
    L = ["# Signal catalogue", "", f"_Generated from `cie/lexicon.py` (rules {VERSIONS['rules']})._ Every signal row stores family, type, value, evidence text, "
         "confidence, method, rule version and the evidence turn (seq, turn_no, trace_id).", ""]
    for fam in FAMILY_CATEGORY:
        rows = [(t, "lexicon", c, d, rx.pattern) for f, t, c, rx, d in TEXT_SIGNALS if f == fam] + [(t, m, None, d, None) for f, t, m, d in DERIVED_SIGNALS if f == fam]
        if not rows:
            continue
        L += [f"## {FAMILY_CATEGORY[fam]} (`{fam}`)", "", "| Type | Method | Confidence | Meaning |", "|---|---|---|---|"]
        L += [f"| `{t}` | {m} | {c if c is not None else '-'} | {d} |" for t, m, c, d, _ in rows]
        L.append("")
    L += ["## Methods", "", "- `lexicon`: regex on redacted customer text; `lexicon@paraphrase`: same regex on the agent's issue paraphrase (confidence x0.9).",
          "- `intent`: emitted from turn intent classification (taxonomy rules).", "- `tool` / `event` / `metadata` / `placeholder` / `gazetteer`: structural evidence.",
          "- `derived`: computed across turns (loops, repeats, abandonment, thread logic).", "- `llm` (not yet enabled): adjudication inside the uncertainty band, see AGENTS.md §2.6.", "",
          "Full regexes are in `cie/lexicon.py`; the UI Signal Catalogue page shows live counts and example evidence."]
    return "\n".join(L) + "\n"


def taxonomy_doc():
    tax = Taxonomy()
    L = [f"# Intent taxonomy {tax.version} (DRAFT for SME review)", "", "_Generated from `taxonomy/taxonomy_v0.yaml`. Stable IDs = codes. L4 variations are added in Week 2 discovery._", "",
         "Classification evidence order: platform label (0.90; generic routing labels 0.60) > customer keyword (0.70, +0.05 on the platform's need-capture turn) > short IVR token (0.50). "
         "Within the same L2, the customer's latest explicit words choose the L3. A representative request is primary only when no other need is stated. Below 0.45 -> `UNKNOWN`.", ""]
    for d in tax.doc["domains"]:
        L += [f"## {d['code']}: {d['name']}", ""]
        for c in d["categories"]:
            L += [f"### {c['code']}: {c['name']}", ""]
            for i in c["intents"]:
                L += [f"**`{i['code']}`: {i['name']}** (family: {i['family']})  ", f"{i['definition']}  ",
                      f"Include: {'; '.join(i.get('include') or [])}  ", f"Exclude: {'; '.join(i.get('exclude') or []) or '-'}  ",
                      f"Platform labels: {', '.join('`' + p + '`' for p in i.get('platform') or []) or '- (keyword rules only)'}", ""]
    return "\n".join(L) + "\n"


def data_dictionary():
    from . import db
    con = sqlite3.connect(":memory:"); db.init(con)
    L = ["# Data dictionary", "", f"_Generated from `cie/db.py` (schema {VERSIONS['schema']}). See `data_model.md` for the ERD and grain rules._", ""]
    for (name,) in con.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"):
        cols = con.execute(f"PRAGMA table_info({name})").fetchall()
        L += [f"## `{name}`", "", "| Column | Type | PK |", "|---|---|---|"] + [f"| {c[1]} | {c[2]} | {'yes' if c[5] else ''} |" for c in cols] + [""]
    return "\n".join(L) + "\n"


def main():
    DOCS.mkdir(exist_ok=True)
    if SAMPLE.exists():
        (DOCS / "W1_source_profile.md").write_text(profile(), encoding="utf-8")
    (DOCS / "signal_catalogue.md").write_text(signal_catalogue(), encoding="utf-8")
    (DOCS / "taxonomy_v0.md").write_text(taxonomy_doc(), encoding="utf-8")
    (DOCS / "data_dictionary.md").write_text(data_dictionary(), encoding="utf-8")
    print("docs written to", DOCS)


if __name__ == "__main__":
    main()
